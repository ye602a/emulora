const fn to_f32(values: &[f64; N_WAVELENGTHS]) -> [f32; N_WAVELENGTHS] {
    let mut result = [0.0; N_WAVELENGTHS];
    let mut i = 0;
    while i < N_WAVELENGTHS {
        result[i] = values[i] as f32;
        i += 1;
    }
    result
}

